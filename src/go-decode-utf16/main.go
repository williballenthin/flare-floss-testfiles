// decodeW decodes into a NUL-terminated UTF-16 buffer, as passed to Windows' wide APIs.
//go:noinline
func decodeW(enc []byte) []uint16 {
	runes := make([]rune, len(enc))
	for i, b := range enc {
		runes[i] = rune(b ^ key[i%len(key)])
	}
	return append(utf16.Encode(runes), 0)
}

