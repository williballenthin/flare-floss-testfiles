// decrypt each string with a fresh RC4 keystream (crypto/rc4).
//go:noinline
func decrypt(enc []byte) string {
	c, err := rc4.NewCipher(rc4Key)
	if err != nil {
		panic(err)
	}
	out := make([]byte, len(enc))
	c.XORKeyStream(out, enc)
	return string(out)
}

